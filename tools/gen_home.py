#!/usr/bin/env python3
"""Generate the TonyFlix Netflix-style home rows from build/home_rows.json.

Writes:
  addons/skin.tonyflix/1080i/Includes_TonyFlix_Home.xml
      One include per tab, `TonyFlix_Rows_<labelID>`, which shortcuts/template.xml
      pulls into that tab's widget grouplist, plus one $VAR per row for its
      content path.
  addons/skin.tonyflix/shortcuts/overrides.xml  (block between TONYFLIX:HERO markers)
      Default hero ("fullscreen widget") path per tab. template.xml reads the hero
      content from $VAR[TonyFlix_Hero_<tab>] so only focused/visited tabs load theirs.

Each row reuses AH2's Widget_Poster (same params as the skinshortcuts template
would pass), with the info header on (Netflix-style title/plot at the top).

Row content is a $VAR that stays EMPTY - so Kodi never calls TMDbHelper - until:
  * its tab has been "visited": focused in the main menu for TAB_SECS (a skin
    timer sets the flag; it then stays set for the session, so rows never reload),
  * Trakt is linked, for Trakt rows (an unlinked Trakt call pops a blocking
    login dialog), and
  * for rows below `eager_rows`: the user has scrolled within `lookahead` rows.
A row is shown (label + spinner) once it may load, because Kodi only re-reads a
list's $VAR path while the list is visible. Timers.xml hides rows that stay
empty for EMPTY_SECS (e.g. an empty Trakt watchlist).
Rows without the `lite` flag are hidden and never loaded on the Lite profile
(Skin.HasSetting(TonyFlix.Lite)).

Control IDs: row list 30000+tab*100+row, label group 31000+..., spacer 32000+...

Usage: python3 tools/gen_home.py
"""
import json
import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape, quoteattr

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "build" / "home_rows.json"
SKIN = ROOT / "addons" / "skin.tonyflix"
OUT = SKIN / "1080i" / "Includes_TonyFlix_Home.xml"
OVERRIDES = SKIN / "shortcuts" / "overrides.xml"
PLUGIN = "plugin://plugin.video.themoviedb.helper/?"
STYLES = {  # style: (widget include, list include, Slide.WidgetAspect)
    "poster": ("Widget_Poster", "List_Poster_Row", "Poster"),
    "landscape": ("Widget_Poster", "List_Landscape_Row", "Landscape"),
    "square": ("Widget_Poster", "List_Square_Row", "Square"),
    "buttons": ("Widget_Submenu", "List_Button_Row", "Button"),
}
TRAKT_LINKED = "[!String.IsEmpty(Window(Home).Property(TMDbHelper.TraktIsAuth)) | Skin.HasSetting(TonyFlix.TraktLinked)]"
NOT_LITE = "!Skin.HasSetting(TonyFlix.Lite)"
TIMERS = SKIN / "1080i" / "Timers.xml"
EMPTY_SECS = 3  # a visible row that is still empty (and not loading) this long gets hidden
TAB_SECS = 1    # a tab must stay focused this long before its rows load (skimming tabs costs nothing)
HERO_BEGIN = "    <!-- TONYFLIX:HERO:BEGIN (generated by tools/gen_home.py) -->\n"
HERO_END = "    <!-- TONYFLIX:HERO:END -->\n"


def tab_focused(tab):
    return f"String.IsEqual(Container(300).ListItem.Property(submenuVisibility),{tab})"


def full_path(query, common):
    if not re.match(r"^info=[a-z_]+(&|$)", query):
        raise ValueError(f"path must start with info=<route>: {query!r}")
    return f"{PLUGIN}{query}&{common}" if common else f"{PLUGIN}{query}"


def items_xml(items, common):
    """Static list items (no plugin call). Each item: label, icon, and either
    `path` (TMDbHelper query, opened full-screen) or `action` (Kodi builtin)."""
    out = ["            <content>\n"]
    for it in items:
        if "path" in it:
            # opened full-screen: no widget-only params (widget=true can suppress prompts)
            action = f'ActivateWindow(Videos,"{full_path(it["path"], "")}",return)'
        else:
            action = it["action"]
        icon = escape(it.get("icon", ""))
        out.append(
            "                <item>\n"
            f"                    <label>{escape(it['label'])}</label>\n"
            f"                    <icon>{icon}</icon>\n"
            f"                    <thumb>{icon}</thumb>\n"
            f"                    <onclick>{escape(action)}</onclick>\n"
            "                </item>\n"
        )
    out.append("            </content>\n")
    return "".join(out)


def row_xml(tab, t, i, row, cfg):
    rid, gid, sid = 30000 + t * 100 + i, 31000 + t * 100 + i, 32000 + t * 100 + i
    widget, include, aspect = STYLES[row.get("style", "poster")]
    kind = "items" if "items" in row else "stack" if row.get("stack") else "path"
    info = row.get("info", kind != "items" and widget == "Widget_Poster")
    look = cfg["lookahead"]
    prev = rid - 1

    visible = [tab_focused(tab)]
    load = [f"!String.IsEmpty(Window(Home).Property(TonyFlix.Visited.{tab}))"]
    if row.get("trakt"):
        visible.append(TRAKT_LINKED)
        load.append(TRAKT_LINKED)
    if not row.get("lite"):
        visible.append(NOT_LITE)
        load.append(NOT_LITE)
    if i >= cfg["eager_rows"]:
        load.append(f"Integer.IsGreaterOrEqual(Window(Home).Property(TonyFlix.Depth.{tab}),{i + 1})")
    if kind == "stack":
        if i == 0:
            raise ValueError(f"{tab} row 0 cannot be a stack (needs a row above)")
        has_prev = f"!Integer.IsEqual(Container({prev}).NumItems,0)"
        visible.append(has_prev)
        load.append(has_prev)

    var = timer = ""
    if kind == "items":
        content = items_xml(row["items"], cfg["common_params"])
        altvisible = "false"
    else:
        value = (f"$INFO[Container({prev}).ListItem.FolderPath]" if kind == "stack"
                 else escape(full_path(row["path"], cfg["common_params"])))
        var = (
            f'    <variable name="TonyFlix_Path_{rid}">\n'
            f'        <value condition={quoteattr(" + ".join(load))}>{value}</value>\n'
            f"    </variable>\n"
        )
        content = (
            f'            <include content="Widget_ContentDynamic">\n'
            f'                <param name="sortby"></param>\n'
            f'                <param name="sortorder"></param>\n'
            f'                <param name="target">videos</param>\n'
            f'                <param name="limit">{cfg["limit"]}</param>\n'
            f'                <param name="autolimit">7</param>\n'
            f'                <param name="is_autolimit">False</param>\n'
            f'                <param name="content">$VAR[TonyFlix_Path_{rid}]</param>\n'
            f"            </include>\n"
        )
        # Kodi only re-evaluates a list's (variable) path while the list is VISIBLE, and
        # Widget_Poster normally hides empty lists - so show the row (label + spinner) as
        # soon as it may load. A skin timer (Timers.xml) hides rows that stay empty.
        altvisible = " + ".join(load + [f"String.IsEmpty(Window(Home).Property(TonyFlix.Empty.{rid}))"])
        timer = (
            f"    <timer>\n"
            f"        <name>tf_empty_{rid}</name>\n"
            f"        <start reset=\"true\">Window.IsActive(Home) + Control.IsVisible({rid}) + Integer.IsEqual(Container({rid}).NumItems,0) + !Container({rid}).IsUpdating</start>\n"
            f"        <stop>Integer.IsGreaterOrEqual(Skin.TimerElapsedSecs(tf_empty_{rid}),{EMPTY_SECS}) | !Control.IsVisible({rid}) | !Integer.IsEqual(Container({rid}).NumItems,0) | Container({rid}).IsUpdating</stop>\n"
            f"        <onstop condition=\"Integer.IsGreaterOrEqual(Skin.TimerElapsedSecs(tf_empty_{rid}),{EMPTY_SECS})\">SetProperty(TonyFlix.Empty.{rid},1,Home)</onstop>\n"
            f"    </timer>\n"
        )

    label = f"$INFO[Container({prev}).ListItem.Label]" if kind == "stack" and not row.get("label") else row["label"]
    depth = i + 1 + look
    p = lambda name, value: f"            <param name={quoteattr(name)} value={quoteattr(str(value))} />\n"
    params = (
        p("groupid", gid) + p("id", rid) + p("spacerid", sid)
        + p("label", label) + p("include", include)
        + p("altvisible", altvisible) + p("visible", " + ".join(visible))
        + p("infowidget", info) + p("infowidget_full", info)
    )
    if widget == "Widget_Poster":
        params += (
            p("usealtlabel", "False") + p("altlabel", "") + p("usewidgetlabel", "False")
            + p("busy_visible", f"Container({rid}).IsUpdating")
            + p("detailed", "false") + p("oversized", "False")
        )
    else:  # Widget_Submenu (button row)
        params += p("detailed", "true")
    info_style = "Full" if info else ""
    xml = (
        f"        <!-- {escape(tab)} row {i}: {escape(row.get('label') or 'stack of row ' + str(i - 1))} ({kind}) -->\n"
        f'        <include content="{widget}">\n'
        + params + content
        + f"            <onfocus>SetProperty(TMDbHelper.WidgetContainer,{rid},Home)</onfocus>\n"
        f"            <onfocus>SetProperty(Slide.WidgetContainer,{rid},Home)</onfocus>\n"
        f"            <onfocus>SetProperty(Slide.WidgetInfoStyle,{info_style},Home)</onfocus>\n"
        f"            <onfocus>SetProperty(Slide.WidgetAspect,{aspect},Home)</onfocus>\n"
        f'            <onfocus condition="!Integer.IsGreaterOrEqual(Window(Home).Property(TonyFlix.Depth.{tab}),{depth})">SetProperty(TonyFlix.Depth.{tab},{depth},Home)</onfocus>\n'
        f"            <onunfocus>ClearProperty(Slide.WidgetAspect,Home)</onunfocus>\n"
        f"            <onunfocus>ClearProperty(Slide.WidgetInfoStyle,Home)</onunfocus>\n"
        f"            <onunfocus>ClearProperty(Slide.WidgetContainer,Home)</onunfocus>\n"
        f"            <onunfocus>ClearProperty(Slide.WidgetTitle,Home)</onunfocus>\n"
        f'            <onback condition="!Integer.IsEqual(Container({rid}).ListItem.CurrentItem,1)">SetFocus({rid},0,absolute)</onback>\n'
        f'            <onback condition="Integer.IsEqual(Container({rid}).ListItem.CurrentItem,1)">SetFocus(300)</onback>\n'
        f"        </include>\n"
    )
    return xml, var, timer


def main():
    cfg = json.loads(CONFIG.read_text())
    tabs = cfg["tabs"]
    if len(tabs) > 9:
        sys.exit("at most 9 tabs (control ID scheme)")
    includes, variables, hero, timers = [], [], [], []
    summary = []
    for t, (tab, spec) in enumerate(tabs.items(), start=1):
        if not re.match(r"^[a-z0-9]+$", tab):
            sys.exit(f"tab key must be a skinshortcuts labelID (a-z0-9): {tab}")
        rows = spec["rows"]
        if len(rows) > 99:
            sys.exit(f"{tab}: at most 99 rows")
        body = []
        for i, row in enumerate(rows):
            if row.get("style", "poster") not in STYLES:
                sys.exit(f"{tab} row {i}: unknown style {row.get('style')}")
            x, v, tm = row_xml(tab, t, i, row, cfg)
            body.append(x)
            if v:
                variables.append(v)
            if tm:
                timers.append(tm)
        includes.append(f'    <include name="TonyFlix_Rows_{tab}">\n' + "".join(body) + "    </include>\n")
        hero_path = escape(full_path(spec["hero"], cfg["common_params"]))
        variables.append(
            f'    <variable name="TonyFlix_Hero_{tab}">\n'
            f'        <value condition={quoteattr(f"{tab_focused(tab)} | !String.IsEmpty(Window(Home).Property(TonyFlix.Visited.{tab}))")}>{hero_path}</value>\n'
            f"    </variable>\n"
        )
        timers.append(
            f"    <timer>\n"
            f"        <name>tf_tab_{tab}</name>\n"
            f'        <start reset="true">Window.IsActive(Home) + {tab_focused(tab)} + String.IsEmpty(Window(Home).Property(TonyFlix.Visited.{tab}))</start>\n'
            f"        <stop>!{tab_focused(tab)} | Integer.IsGreaterOrEqual(Skin.TimerElapsedSecs(tf_tab_{tab}),{TAB_SECS})</stop>\n"
            f'        <onstop condition="{tab_focused(tab)} + Integer.IsGreaterOrEqual(Skin.TimerElapsedSecs(tf_tab_{tab}),{TAB_SECS})">SetProperty(TonyFlix.Visited.{tab},1,Home)</onstop>\n'
            f"    </timer>\n"
        )
        hero.append(f'    <propertydefault labelID="{tab}" property="widgetPath">{hero_path}</propertydefault>\n')
        hero.append(f'    <propertydefault labelID="{tab}" property="widgetTarget">videos</propertydefault>\n')
        for i, r in enumerate(rows):
            if sum(k in r for k in ("path", "items", "stack")) != 1:
                sys.exit(f"{tab} row {i}: needs exactly one of path / items / stack")
        lite = sum(1 for r in rows if r.get("lite"))
        trakt = sum(1 for r in rows if r.get("trakt"))
        summary.append(f"  {tab}: {len(rows)} rows ({lite} lite, {trakt} trakt)")

    OUT.write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        "<!-- GENERATED by tools/gen_home.py from build/home_rows.json - edit the JSON, not this file. -->\n"
        "<includes>\n" + "".join(includes) + "\n" + "".join(variables) + "</includes>\n",
        encoding="utf-8",
    )

    TIMERS.write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        "<!-- GENERATED by tools/gen_home.py: hides home rows that finished loading empty. -->\n"
        "<timers>\n" + "".join(timers) + "</timers>\n",
        encoding="utf-8",
    )

    text = OVERRIDES.read_text(encoding="utf-8")
    block = HERO_BEGIN + "".join(hero) + HERO_END
    if HERO_BEGIN in text:
        text = re.sub(re.escape(HERO_BEGIN) + r".*?" + re.escape(HERO_END), lambda _: block, text, flags=re.S)
    else:
        anchor = "    <!-- Default Widgets Set -->\n"
        if anchor not in text:
            sys.exit("overrides.xml: anchor for hero block not found")
        text = text.replace(anchor, block + "\n" + anchor, 1)
    OVERRIDES.write_text(text, encoding="utf-8")

    print(f"Wrote {OUT.relative_to(ROOT)}, {TIMERS.relative_to(ROOT)} and hero defaults in {OVERRIDES.relative_to(ROOT)}")
    print("\n".join(summary))


if __name__ == "__main__":
    main()
