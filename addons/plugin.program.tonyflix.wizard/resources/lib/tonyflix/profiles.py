# TonyFlix performance profiles: hardware detection + applying a profile inside Kodi.
#
# Data comes from resources/data/profiles.json (synced from build/profiles/profiles.json
# by tools/build_repo.py). Order of application: `common`, then the chosen profile.
import json
import os
import platform
import re
import sys
import time
import xml.etree.ElementTree as ET

import xbmc
import xbmcaddon
import xbmcvfs

ADDON = xbmcaddon.Addon("plugin.program.tonyflix.wizard")
ADDON_PATH = xbmcvfs.translatePath(ADDON.getAddonInfo("path"))
DATA = os.path.join(ADDON_PATH, "resources", "data")
PROFILE_DIR = xbmcvfs.translatePath("special://profile/")
STATE_FILE = os.path.join(xbmcvfs.translatePath(ADDON.getAddonInfo("profile")), "state.json")
SKIN_ID = "skin.tonyflix"
GENERATED_MARK = "Generated by TonyFlix"


def log(msg, level=xbmc.LOGINFO):
    xbmc.log(f"[TonyFlix] {msg}", level)


def load_profiles():
    with open(os.path.join(DATA, "profiles.json"), encoding="utf-8") as f:
        return json.load(f)


# ---------------------------------------------------------------- detection

def _ram_mb():
    # Kodi reports e.g. "3825MB"; fall back to /proc/meminfo on Linux/Android.
    label = xbmc.getInfoLabel("System.Memory(total)")
    m = re.search(r"([\d.]+)\s*([GM])B", label or "", re.I)
    if m:
        val = float(m.group(1))
        return int(val * 1024 if m.group(2).upper() == "G" else val)
    try:
        with open("/proc/meminfo") as f:
            for line in f:
                if line.startswith("MemTotal:"):
                    return int(line.split()[1]) // 1024
    except OSError:
        pass
    return 0


def _gpu():
    # System.VideoEncoderInfo is filled asynchronously ("Busy" first), e.g. "GPU: Mali-T720".
    for _ in range(20):
        label = xbmc.getInfoLabel("System.VideoEncoderInfo")
        if label and label.lower() not in ("busy", "system.videoencoderinfo"):
            return label.split(":", 1)[-1].strip()
        xbmc.sleep(250)
    return ""


def _soc():
    # Android/Linux: "Hardware : sun50iw6" (Allwinner H6), "sm1" (Amlogic S905X3) ...
    try:
        with open("/proc/cpuinfo") as f:
            for line in f:
                if line.split(":")[0].strip() in ("Hardware", "model name", "Model"):
                    return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return ""


def detect_hardware():
    return {
        "ram_mb": _ram_mb(),
        "cpu_cores": os.cpu_count() or 0,
        "kodi_64bit": sys.maxsize > 2 ** 32,
        "machine": platform.machine(),
        "gpu": _gpu(),
        "soc": _soc(),
        "platform": "android" if xbmc.getCondVisibility("System.Platform.Android") else sys.platform,
    }


def suggest_profile(hw, rules):
    """Return ('lite'|'standard', [reasons])."""
    reasons = []
    if hw["ram_mb"] and hw["ram_mb"] < rules["lite_if_ram_mb_below"]:
        reasons.append(f"{hw['ram_mb']} MB RAM")
    if hw["cpu_cores"] and hw["cpu_cores"] < rules["lite_if_cpu_cores_below"]:
        reasons.append(f"{hw['cpu_cores']} CPU cores")
    if rules.get("lite_if_32bit_kodi") and not hw["kodi_64bit"]:
        reasons.append("32-bit Kodi")
    gpu = hw["gpu"].lower()
    for weak in rules.get("lite_if_gpu_matches", []):
        if weak.lower() in gpu:
            reasons.append(f"GPU {hw['gpu']}")
            break
    soc = hw.get("soc", "").lower()
    for weak in rules.get("lite_if_soc_matches", []):
        if weak.lower() in soc:
            reasons.append(f"chip {hw['soc']}")
            break
    return ("lite" if reasons else "standard"), reasons


# ---------------------------------------------------------------- applying

def _jsonrpc(method, params):
    req = json.dumps({"jsonrpc": "2.0", "id": 1, "method": method, "params": params})
    return json.loads(xbmc.executeJSONRPC(req))


def _merged(cfg, name, key):
    out = {}
    for part in (cfg["common"].get(key, {}), cfg[name].get(key, {})):
        for k, v in part.items():
            if isinstance(v, dict) and isinstance(out.get(k), dict):
                out[k] = {**out[k], **v}
            else:
                out[k] = v
    return out


def apply_guisettings(settings, report):
    for sid, value in settings.items():
        res = _jsonrpc("Settings.SetSettingValue", {"setting": sid, "value": value})
        if res.get("result") is True:
            report["gui_ok"].append(sid)
        else:
            # Platform-specific ids (e.g. videoscreen.limitgui off Android) don't exist here.
            report["gui_skipped"].append(f"{sid}: {res.get('error', {}).get('message', res)}")


def _advanced_xml(settings):
    root = ET.Element("advancedsettings", version="1.0")

    def add(parent, d):
        for k, v in d.items():
            el = ET.SubElement(parent, k)
            if isinstance(v, dict):
                add(el, v)
            else:
                el.text = str(v)
    add(root, settings)
    ET.indent(root, space="    ")
    return f"<!-- {GENERATED_MARK} - performance profile. Edit build/profiles/profiles.json instead. -->\n" \
           + ET.tostring(root, encoding="unicode") + "\n"


def write_advancedsettings(settings, report):
    path = os.path.join(PROFILE_DIR, "advancedsettings.xml")
    if os.path.exists(path):
        with open(path, encoding="utf-8", errors="replace") as f:
            current = f.read()
        if GENERATED_MARK not in current:  # someone else's file: keep a copy
            backup = path + f".bak-{time.strftime('%Y%m%d-%H%M%S')}"
            with open(backup, "w", encoding="utf-8") as f:
                f.write(current)
            report["notes"].append(f"existing advancedsettings.xml backed up to {os.path.basename(backup)}")
    with open(path, "w", encoding="utf-8") as f:
        f.write(_advanced_xml(settings))
    report["advancedsettings"] = path


def apply_addon_settings(addons, report):
    # One add-on, one setting at a time: parallel setSetting calls overwrite each other.
    for aid, settings in addons.items():
        if not xbmc.getCondVisibility(f"System.HasAddon({aid})"):
            report["addon_skipped"].append(f"{aid} (not installed)")
            continue
        addon = xbmcaddon.Addon(aid)
        for sid, value in settings.items():
            if sid.startswith("_"):
                continue
            addon.setSetting(sid, str(value))
            report["addon_ok"].append(f"{aid}:{sid}={value}")


def _skin_settings_file():
    return os.path.join(PROFILE_DIR, "addon_data", SKIN_ID, "settings.xml")


def apply_skin(set_bool, reset, report):
    if xbmc.getSkinDir() == SKIN_ID:
        for b in set_bool:
            xbmc.executebuiltin(f"Skin.SetBool({b})")
        for b in reset:
            xbmc.executebuiltin(f"Skin.Reset({b})")
        report["skin_mode"] = "builtins (TonyFlix active)"
        return
    # TonyFlix isn't the active skin yet: edit its stored settings so they apply when it loads.
    path = _skin_settings_file()
    os.makedirs(os.path.dirname(path), exist_ok=True)
    root = ET.parse(path).getroot() if os.path.exists(path) else ET.Element("settings", version="2")
    by_id = {s.get("id"): s for s in root.findall("setting")}
    for b in reset:
        if b in by_id:
            root.remove(by_id.pop(b))
    for b in set_bool:
        el = by_id.get(b)
        if el is None:  # (an Element with no children is falsy - don't use `or`)
            el = ET.SubElement(root, "setting", id=b, type="bool")
        el.set("type", "bool")
        el.text = "true"
    ET.indent(root, space="    ")
    ET.ElementTree(root).write(path, encoding="utf-8", xml_declaration=False)
    report["skin_mode"] = f"settings file ({path})"


def apply_profile(name):
    cfg = load_profiles()
    if name == "auto":
        name, _ = suggest_profile(detect_hardware(), cfg["detection"])
    if name not in ("lite", "standard"):
        raise ValueError(f"unknown profile {name}")
    report = {"profile": name, "gui_ok": [], "gui_skipped": [], "addon_ok": [], "addon_skipped": [], "notes": []}
    apply_guisettings(_merged(cfg, name, "guisettings"), report)
    write_advancedsettings(_merged(cfg, name, "advancedsettings"), report)
    apply_addon_settings(_merged(cfg, name, "addons"), report)
    skin_common, skin_prof = cfg["common"].get("skin", {}), cfg[name].get("skin", {})
    set_bool = list(dict.fromkeys(skin_common.get("set_bool", []) + skin_prof.get("set_bool", [])))
    reset = [b for b in dict.fromkeys(skin_common.get("reset", []) + skin_prof.get("reset", [])) if b not in set_bool]
    apply_skin(set_bool, reset, report)
    os.makedirs(os.path.dirname(STATE_FILE), exist_ok=True)
    with open(STATE_FILE, "w", encoding="utf-8") as f:
        json.dump({"profile": name, "applied": time.strftime("%Y-%m-%d %H:%M:%S"), "report": report}, f, indent=1)
    log(f"profile '{name}' applied: {len(report['gui_ok'])} GUI settings, {len(report['addon_ok'])} add-on settings, "
        f"skipped {report['gui_skipped'] + report['addon_skipped']}, skin via {report['skin_mode']}")
    return report


def current_profile():
    try:
        with open(STATE_FILE, encoding="utf-8") as f:
            return json.load(f).get("profile")
    except (OSError, ValueError):
        return None
